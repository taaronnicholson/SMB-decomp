#!/usr/bin/env python3
"""Summarise each player state handler (src/fixed.s, labels PlayerStateNN) into docs/player_states.md.
Static analysis: estimates each handler's extent, then reports the states it can switch to, buttons it tests, sound effects, and key calls."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'src/fixed.s')).read().split('\n')
labels = {}
for i, l in enumerate(src):
    m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*):', l)
    if m: labels[m.group(1)] = i
BTN = {0x01: 'A', 0x02: 'B', 0x04: 'Select', 0x08: 'Start', 0x10: 'Right', 0x20: 'Left', 0x40: 'Up', 0x80: 'Down'}
def region(start, seen=None, depth=0):
    seen = seen if seen is not None else set()
    if start in seen: return []
    seen.add(start); out = []; i = start; far = start
    while i < len(src) and i - start < 500:
        l = src[i].strip(); out.append(l)
        m = re.match(r'^(?:BNE|BEQ|BCC|BCS|BMI|BPL|BVC|BVS) (\w+)$', l)
        if m and m.group(1) in labels and labels[m.group(1)] > i: far = max(far, labels[m.group(1)])
        if l in ('RTS', 'RTI') and i >= far: break
        mj = re.match(r'^JMP (\w+)$', l)
        if mj and i >= far:
            if depth < 2 and mj.group(1) in labels and labels[mj.group(1)] != i: out += region(labels[mj.group(1)], seen, depth + 1)
            break
        i += 1
    return out
rows = []
for name in sorted(labels, key=lambda n: labels[n]):
    m = re.match(r'^PlayerState([0-9A-F]{2})$', name)
    if not m: continue
    s = int(m.group(1), 16); lines = region(labels[name]); trans = []; btn = set(); sfx = []; calls = set(); prev = ''; lastbtn = None
    for l in lines:
        if re.match(r'^STA player_state$', l):
            ml = re.match(r'^LDA #\$([0-9A-F]{2})$', prev)
            if ml: trans.append(ml.group(1))
        mb = re.match(r'^LDA (buttons|buttons_pressed)$', l)
        if mb: lastbtn = mb.group(1)
        ma = re.match(r'^AND #\$([0-9A-F]{2})$', l)
        if ma and lastbtn:
            v = int(ma.group(1), 16)
            if v in BTN: btn.add(BTN[v] + ('*' if lastbtn == 'buttons_pressed' else ''))
            lastbtn = None
        mj = re.match(r'^JSR (PlaySfx\w+)$', l)
        if mj and re.match(r'^LDA #\$([0-9A-F]{2})$', prev): sfx.append(re.match(r'^LDA #\$([0-9A-F]{2})$', prev).group(1) + ' ' + mj.group(1)[7:].lower())
        mc = re.match(r'^JSR (HurtPlayer|GetTileSpecial|GetMapTile|SetCollectedFlag|AddScore|FindFreeEntitySlot|SpawnEffects)$', l)
        if mc: calls.add(mc.group(1))
        prev = l
    rows.append((s, name, len(lines), sorted(set(trans), key=trans.index), sorted(btn), sorted(set(sfx)), sorted(calls)))
os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
with open(os.path.join(ROOT, 'docs/player_states.md'), 'w') as f:
    f.write('# Player states\n\nGenerated by `tools/summarize_player.py` from `src/fixed.s` (static analysis; extents are estimates). `player_state` (`$63`) indexes\n`PlayerStateHandlers` (bank 2 `$B5AA`); the handler runs with the map bank mapped. Buttons: A `$01`, B `$02`, Select `$04`, Start `$08`, Right `$10`,\nLeft `$20`, Up `$40`, Down `$80` (`*` = tested on a fresh press, `buttons_pressed`).\n\n')
    f.write('| State | Handler | Lines | Can switch to | Buttons | Sound | Calls |\n|---|---|---|---|---|---|---|\n')
    for s, n, ln, tr, b, sf, c in rows:
        f.write(f"| ${s:02X} | `{n}` | {ln} | {', '.join('$' + t for t in tr) or '-'} | {', '.join(b) or '-'} | {', '.join(sf) or '-'} | {', '.join(c) or '-'} |\n")
print(len(rows), 'states summarised')
