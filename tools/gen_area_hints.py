#!/usr/bin/env python3
"""Generate tools/hints_areas.txt: the 24-entry area table in bank 0 (header pointers, map banks, headers)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b0 = d[16:16 + 16384]
def by(a): return b0[a - 0x8000]
LO, HI, BANK, N = 0x83B9, 0x83D1, 0x83E9, 24
out = ['; generated by tools/gen_area_hints.py -- do not edit by hand',
       f'dlohi 0 {LO:X} {HI:X} {N}', f'name 0 {LO:X} AreaHeaderPtrLo', f'name 0 {HI:X} AreaHeaderPtrHi',
       f'name 0 {BANK:X} AreaMapBank', f'struct 0 {BANK:X} 1 ' + 'b' * N + '   ; PRG bank holding each area\'s map']
for i in range(N):
    h = by(LO + i) | by(HI + i) << 8
    out.append(f'name 0 {h:X} AreaHeader{i}')
    out.append(f'struct 0 {h:X} 1 bwbbbwbbbb   ; song, map address, log2 width, height, palette set, object ptr, byte8, byte9, initial game_state, tileset')
open(os.path.join(ROOT, 'tools/hints_areas.txt'), 'w').write('\n'.join(out) + '\n')
print(N, 'areas')
