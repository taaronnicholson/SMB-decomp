#!/usr/bin/env python3
"""Generate tools/hints_anim.txt: entity animation groups in bank 1 (pointer table $8D7D, 31 groups).
Group -> word table of frame offsets (relative to each word's own address); frame = count byte + count * (dx16, dy16, tile, attr)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b1 = d[16 + 16384:16 + 2 * 16384]
def by(a): return b1[a - 0x8000]
def wd(a): return by(a) | by(a + 1) << 8
T, N = 0x8D7D, 31
# appearance of each group as rendered by tools/render_sprites.py (not behaviour); only groups seen in stages 0-5 are listed
DESCR = {0: 'green dome balloon on a stalk, a star, score popups 10-1000 (all stages)',
         2: 'green worm (stage 0)', 3: 'small purple/yellow shapes and bubbles (stage 5)', 7: 'small purple winged shape (stage 3)',
         11: 'green snail-like creature (stages 1, 2, 4)', 13: 'purple dome blob (stages 2, 3, 4)',
         14: 'red creature with a propeller (stages 0, 3)', 15: 'white and black creature (stages 0, 1, 3, 4)',
         17: 'small green curls (stages 2, 4)', 23: 'green butterfly (stages 0, 1, 2, 3, 4)',
         24: 'large green spiky creature (stage 5)', 27: 'green grass-like creature and purple slug (stages 2, 3)'}
out = ['; generated by tools/gen_anim_hints.py -- do not edit by hand',
       f'name 1 {T:X} AnimGroupPtrs', f'dwords 1 {T:X} {N}']
groups = {}
for g in range(N): groups.setdefault(wd(T + 2 * g), []).append(g)
frames = {}
for P, gs in sorted(groups.items()):
    n = wd(P) // 2
    out.append(f'blob 1 {P:X} {2 * n} AnimGroup{gs[0]} frame offsets for entity animation group(s) {",".join(map(str, gs))}: {n} frames{" - " + DESCR[gs[0]] if gs[0] in DESCR else ""}')
    out.append(f'struct 1 {P:X} {n} w')
    for f in range(n):
        a = P + 2 * f; frames.setdefault(a + wd(a), []).append(gs[0])
taken = []
for a, gs in sorted(frames.items()):
    n = by(a); end = a + 1 + 6 * n
    if any(not (end <= s or a >= e) for s, e in taken): continue    # overlaps an earlier frame: leave as plain data
    taken.append((a, end))
    out.append(f'struct 1 {a:X} 1 b')
    if n: out.append(f'struct 1 {a + 1:X} {n} wwbb')
open(os.path.join(ROOT, 'tools/hints_anim.txt'), 'w').write('\n'.join(out) + '\n')
print(len(groups), 'groups,', len(taken), 'frames')
