#!/usr/bin/env python3
"""Generate tools/hints_sound.txt: song table, pattern lists and decoded pattern streams (bank 6)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b = d[16 + 6 * 16384:16 + 7 * 16384]
def w(a): return b[a - 0x8000] | b[a - 0x8001 + 2] << 8
def by(a): return b[a - 0x8000]
SONGS, TAB = 9, 0x9427
streams = []
out = ['; generated by tools/gen_sound_hints.py -- do not edit by hand',
       f'struct 6 {TAB:X} {SONGS} bpppp   ; song table: tempo, pulse1/pulse2/triangle/noise pattern lists',
       'name 6 9427 SongTable', 'struct 6 88E2 79 w', 'name 6 88E2 PeriodTable']
lists = {}
def add_list(p):
    n = 0
    while w(p + 2 * n) != 0: n += 1
    lists[p] = n
for s in range(SONGS):
    for c in range(4):
        p = w(TAB + 9 * s + 1 + 2 * c)
        if p not in lists: add_list(p)
LEN2 = {0xF4, 0xF6, 0xF7, 0xFA, 0xFB, 0xFC, 0xFD}
def inside(a):   # inside an already known list (incl. terminator)?
    return any(p <= a < p + 2 * n + 2 for p, n in lists.items())
done = set(); bad = []
changed = True
while changed:
    changed = False
    for p, n in sorted(lists.items()):
        for i in range(n):
            a = w(p + 2 * i)
            if a in done: continue
            done.add(a); start = a
            while True:
                o = by(a)
                if o in LEN2: a += 2
                elif o == 0xF5:
                    t = w(a + 1)                      # F5: switch to a new pattern list
                    if not inside(t): add_list(t); changed = True
                    a += 3; break
                elif o in (0xFE, 0xFF): a += 1; break
                elif o in (0xF8, 0xF9) or o < 0x80: a += 1
                else: bad.append((start, a, o)); break
            streams.append((start, a - start))
            changed = True if False else changed
    # lists may have grown while iterating; loop until stable
for p, n in sorted(lists.items()):
    out.append(f'struct 6 {p:X} {n} p')
    out.append(f'struct 6 {p + 2 * n:X} 1 w   ; list terminator (loop to start)')
for st, ln in sorted(set(streams)):
    out.append(f'stream 6 {st:X} {ln}')
# ---- RAM layout of the four channel state blocks (stride $13 from $0759) ----
FIELDS = ['stream_lo', 'stream_hi', 'list_lo', 'list_hi', 'listpos_lo', 'listpos_hi', 'transpose',
          'next_len', 'len_count', 'duty', 'sweep', 'pitchmod_pos', 'pitchmod_idx', 'period_lo',
          'env_pos', 'env_speed', 'env_count', 'env_idx', 'env_active']
for ci, cn in enumerate(['sq1', 'sq2', 'tri', 'noi']):
    for fi, fn in enumerate(FIELDS):
        out.append(f'ram {0x759 + 0x13 * ci + fi:04X} snd_{cn}_{fn}')
# ---- envelopes (speed byte, volume nibbles, final byte has bit 7 = hold) and pitch-mod tables ----
ENV_LO, ENV_HI, NENV, PIT_LO, PIT_HI, NPIT = 0x930D, 0x9322, 21, 0x93CB, 0x93D4, 9
out += [f'dlohi 6 {ENV_LO:X} {ENV_HI:X} {NENV}', f'dlohi 6 {PIT_LO:X} {PIT_HI:X} {NPIT}',
        f'name 6 {ENV_LO:X} EnvelopePtrLo', f'name 6 {ENV_HI:X} EnvelopePtrHi',
        f'name 6 {PIT_LO:X} PitchModPtrLo', f'name 6 {PIT_HI:X} PitchModPtrHi']
envs = sorted({by(ENV_LO + i) | by(ENV_HI + i) << 8 for i in range(NENV)})
end = PIT_LO
for i in range(NENV):
    a = by(ENV_LO + i) | by(ENV_HI + i) << 8
    nxt = min([e for e in envs if e > a] + [end])
    out.append(f'name 6 {a:X} Envelope{i}')
    out.append(f'struct 6 {a:X} 1 ' + 'b' * (nxt - a) + '   ; speed, volumes..., final byte bit7 = hold')
pits = sorted({by(PIT_LO + i) | by(PIT_HI + i) << 8 for i in range(NPIT)})
for i in range(NPIT):
    a = by(PIT_LO + i) | by(PIT_HI + i) << 8
    nxt = min([e for e in pits if e > a] + [TAB])
    out.append(f'name 6 {a:X} PitchMod{i}')
    out.append(f'struct 6 {a:X} 1 ' + 'b' * (nxt - a) + '   ; signed period offsets, $80 = loop')
# ---- sound effects: 75 x 14-byte definitions via pointer table, plus 16 SFX volume sequences ----
SFX_TAB, NSFX, SEQ_TAB, NSEQ, SEQ_END = 0x8DBD, 75, 0x926D, 16, ENV_LO
def wd(a): return by(a) | by(a + 1) << 8
out += [f'name 6 {SFX_TAB:X} SfxDefPtrs', f'dwords 6 {SFX_TAB:X} {NSFX}   ; pointers to 14-byte SFX definitions',
        f'name 6 {SEQ_TAB:X} SfxSeqPtrs', f'dwords 6 {SEQ_TAB:X} {NSEQ}   ; pointers to SFX volume sequences']
for i in range(NSFX):
    a = wd(SFX_TAB + 2 * i)
    out.append(f'name 6 {a:X} SfxDef{i}')
    out.append(f'struct 6 {a:X} 1 ' + 'b' * 14)
sq = sorted({wd(SEQ_TAB + 2 * i) for i in range(NSEQ)})
for i in range(NSEQ):
    a = wd(SEQ_TAB + 2 * i)
    nxt = min([e for e in sq if e > a] + [SEQ_END])
    out.append(f'name 6 {a:X} SfxSeq{i}')
    out.append(f'struct 6 {a:X} 1 ' + 'b' * (nxt - a))
out += ['name 6 8980 Sound_PlaySfxSq1       ; A = sfx id (0-74)', 'name 6 89EC Sound_PlaySfxSq2', 'name 6 8A6F Sound_PlaySfxNoise']
out += ['ram 074A snd_playing', 'ram 074B snd_sfx_sq1', 'ram 074C snd_sfx_sq2', 'ram 074D snd_sfx_noise',
        'ram 074E snd_tempo', 'ram 074F snd_tempo_base', 'ram 0756 snd_tempo_acc', 'ram 0757 snd_song_transpose',
        'ram 0758 snd_song_ended',
        'ram 07A5 snd_out_sq1_vol', 'ram 07A7 snd_out_sq1_lo', 'ram 07A8 snd_out_sq1_hi',
        'ram 07A9 snd_out_sq2_vol', 'ram 07AB snd_out_sq2_lo', 'ram 07AF snd_out_tri_lo',
        'ram 07B1 snd_out_noi_vol', 'ram 07B3 snd_out_noi_lo',
        'entry 6 8000', 'entry 6 800C', 'entry 6 800F', 'entry 6 8012',
        'name 6 8015 Sound_PlaySong      ; A = song number (0-8): 9-byte header per song in SongTable',
        'name 6 80EA Sound_Silence', 'name 6 80DC Sound_Resume',
        'name 6 81A5 Snd_Sq1_Step', 'name 6 83A0 Snd_Sq2_Step', 'name 6 859B Snd_Tri_Step', 'name 6 8733 Snd_Noise_Step',
        'name 6 8342 Snd_Sq1_Effects', 'name 6 853D Snd_Sq2_Effects', 'name 6 86FC Snd_Tri_Effects', 'name 6 886B Snd_Noise_Effects']
open(os.path.join(ROOT, 'tools/hints_sound.txt'), 'w').write('\n'.join(out) + '\n')
print('lists', len(lists), 'streams', len(set(streams)), 'bad', bad)
