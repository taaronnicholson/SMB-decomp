#!/usr/bin/env python3
"""Write docs/open_items.md: what is still unnamed (RAM bytes with address names, generic Tbl_ tables, bare Bn_/F_ labels) and why.
Generated from src/*.s and tools/hints_tables.txt; `make regen` runs it."""
import os, re, glob, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = sorted(glob.glob(os.path.join(ROOT, 'src/*.s')))
sym = re.compile(r'\b(zp_[0-9A-F]{2}|ram_[0-9A-F]{4})\b')
ops = collections.defaultdict(collections.Counter); where = collections.defaultdict(collections.Counter)
labels = []
for f in files:
    cur = '?'
    for l in open(f):
        m = re.match(r'^([A-Za-z_]\w*):', l)
        if m:
            cur = m.group(1)
            if re.match(r'^(?:F|B\d)_[0-9A-F]{4}$', cur): labels.append((os.path.basename(f), cur))
        mm = re.match(r'^\s+([A-Z]{3}) ', l)
        if not mm: continue
        for s in set(sym.findall(l.split(';')[0])):
            ops[s][mm.group(1)] += 1
            where[s][re.sub(r'_L[0-9A-F]{4}$', '', cur)] += 1
WRITE = {'STA', 'STX', 'STY'}
groups = collections.defaultdict(list)
for s in sorted(ops, key=lambda x: (int(x[3:], 16) if x.startswith('zp_') else 0x1000 + int(x[4:], 16))):
    o = ops[s]; n = sum(o.values()); routines = sorted(where[s])
    if all(k in WRITE for k in o): kind = 'write-only'
    elif not any(k in WRITE or k in ('INC', 'DEC', 'ASL', 'LSR', 'ROL', 'ROR') for k in o): kind = 'read-only'
    elif len(routines) >= 3: kind = 'shared by several routines'
    else: kind = 'used by 1-2 routines'
    groups[kind].append((s, n, routines))
tables = []
for ln in open(os.path.join(ROOT, 'tools/hints_tables.txt')):
    t = ln.split(None, 5)
    if len(t) >= 5 and t[0] == 'blob' and re.match(r'^(Tbl_|\w+_Tbl_[0-9A-F]{4}$)', t[4]):
        tables.append((t[1], t[2], t[3], t[4], t[5].strip() if len(t) > 5 else ''))
out = ['# Open items (generated by `tools/list_open_items.py`)', '',
       'What still has no meaningful name, and why. These are not bugs: the ROM rebuilds byte for byte regardless. Everything here is either a byte whose role',
       'could not be pinned to one meaning, or a small table whose reader is a routine that is itself not yet understood.', '',
       f'## RAM symbols with address names ({sum(len(v) for v in groups.values())})', '']
why = {'write-only': 'written but never read by any code in the ROM (nothing to base a meaning on)',
       'read-only': 'read but never written by code (initialised by the area loader or hardware)',
       'shared by several routines': 'used by three or more routines, usually as scratch for unrelated jobs, so one name would mislead',
       'used by 1-2 routines': 'used by one or two routines whose purpose is not settled'}
for kind in ('write-only', 'read-only', 'shared by several routines', 'used by 1-2 routines'):
    g = groups.get(kind, [])
    if not g: continue
    out += [f'### {kind.capitalize()} ({len(g)})', why[kind], '']
    for s, n, routines in g:
        out.append(f'- `{s}` ({n} uses): ' + ', '.join(f'`{r}`' for r in routines[:4]) + (' ...' if len(routines) > 4 else ''))
    out.append('')
out += [f'## Tables with generic names ({len(tables)})', 'Each has the routines that read it in its comment in `src/`; they are small (a few bytes to about 100) and mostly per-entity motion or frame lists.', '']
for b, a, ln_, nm, cm in tables:
    out.append(f'- bank {b} `${a}` {ln_} bytes `{nm}`' + (f' - {cm}' if cm else ''))
out += ['', f'## Bare address labels ({len(labels)})', 'Labels that are neither local (`@...`) nor given a routine-relative name; mostly interior points of data tables.', '']
for f, n in labels:
    out.append(f'- `{n}` ({f})')
open(os.path.join(ROOT, 'docs/open_items.md'), 'w').write('\n'.join(out) + '\n')
print('open items:', sum(len(v) for v in groups.values()), 'RAM symbols,', len(tables), 'tables,', len(labels), 'labels')
