#!/usr/bin/env python3
"""Generate tools/hints_gamestate.txt: the game-state dispatch table (bank 4 $ADE1, 28 entries, indexed by game_state)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b4 = d[16 + 4 * 16384:16 + 5 * 16384]
def wd(a): return b4[a - 0x8000] | b4[a - 0x7FFF] << 8
T, N = 0xADE1, 28
DESCR = {0x00: 'normal play (no-op) [v]', 0x08: 'entering area 4 after the balloon ride [v]', 0x09: 'area 4 set-up: camera mode 1, timers; waits for player_state != $09, then $0D [v]',
         0x0A: 'bonus tally: appends rows of text from $B074 at a steady pace [v]', 0x0B: 'bonus tally, second phase (score and extra life added) [v]',
         0x0D: 'bonus ascent in area 4 [v]', 0x12: 'game over: set after the YOUR QUEST IS OVER text (B4_B4CE; code-read)'}
out = ['; generated by tools/gen_gamestate_hints.py -- do not edit by hand', f'name 4 {T:X} GameStateHandlers', f'words 4 {T:X} {N} 4']
first = {}
for s in range(N): first.setdefault(wd(T + 2 * s), s)
for a, s in sorted(first.items(), key=lambda kv: kv[1]):
    also = [t for t in range(N) if wd(T + 2 * t) == a and t != s]
    out.append(f'name {"f" if a >= 0xC000 else 4} {a:X} GameState{s:02X}   ; game_state ${s:02X}' + (f' (also {", ".join("$%02X" % t for t in also)})' if also else '') + (f' - {DESCR[s]}' if s in DESCR else ''))
open(os.path.join(ROOT, 'tools/hints_gamestate.txt'), 'w').write('\n'.join(out) + '\n')
print(len(first), 'distinct game-state handlers')
