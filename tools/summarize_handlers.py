#!/usr/bin/env python3
"""Summarise each entity type's handler from the generated source (src/bank5.s) into docs/entity_handlers.md.

Mechanical, static analysis only: the extent of a handler is estimated (up to the first RTS/JMP past the furthest forward
branch, then following one tail JMP), and we report which shared routines it calls, which types it turns into
(LDA #n / STA ent_type), which sound effects it starts, and which game counters it changes."""
import os, re, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'src/bank5.s')).read().split('\n')
labels = {}
for i, l in enumerate(src):
    m = re.match(r'^(@?[A-Za-z_][A-Za-z0-9_]*):', l)
    if m: labels[m.group(1)] = i
def region(start, seen=None, depth=0):
    seen = seen if seen is not None else set()
    if start in seen: return []
    seen.add(start)
    out = []; i = start; far = start
    while i < len(src):
        l = src[i].strip(); out.append(l)
        m = re.match(r'^(B[A-Z]{2}|BNE|BEQ|BCC|BCS|BMI|BPL|BVC|BVS) (@?[A-Za-z_][A-Za-z0-9_]*)$', l)
        if m and m.group(2) in labels and labels[m.group(2)] > i: far = max(far, labels[m.group(2)])
        if re.match(r'^(RTS|RTI)$', l) and i >= far: break
        mj = re.match(r'^JMP (@?[A-Za-z_][A-Za-z0-9_]*)$', l)
        if mj and i >= far:
            if depth < 2 and mj.group(1) in labels and labels[mj.group(1)] != i: out += region(labels[mj.group(1)], seen, depth + 1)
            break
        i += 1
        if i - start > 400: break
    return out
SFX = {'PlaySfxSq1': 'sq1', 'PlaySfxSq2': 'sq2', 'PlaySfxNoise': 'noise'}
TAGS = {'HurtPlayer': 'hurts player', 'Ent_PatrolStep': 'patrols', 'SetEntityPolarPos': 'polar motion', 'GetTileSpecial': 'special-tile lookup',
        'Ent_CheckPlayerOverlap': 'overlap test', 'Ent_CheckPlayerTouch': 'touch test', 'GetMapTile': 'reads map', 'GetTilePropsAtPos': 'reads tile props'}
rows = []
for name in sorted((n for n in labels if re.match(r'^Ent[0-9A-F]{2}_Update$', n)), key=lambda n: int(n[3:5], 16)):
    m = re.match(r'^Ent([0-9A-F]{2})_Update$', name)
    if not m: continue
    t = int(m.group(1), 16); lines = region(labels[name])
    becomes = []; sfx = []; tags = set(); counters = set(); prev = ''
    for l in lines:
        mm = re.match(r'^STA (?:ent_type|ram_0480),[xy]$', l); ml = re.match(r'^LDA #\$([0-9A-F]{2})$', prev)
        if mm and ml: becomes.append(ml.group(1))
        mj = re.match(r'^JSR (\w+)$', l)
        if mj:
            if mj.group(1) in SFX and ml: sfx.append(f'${ml.group(1)} {SFX[mj.group(1)]}')
            if mj.group(1) in TAGS: tags.add(TAGS[mj.group(1)])
        mi = re.match(r'^(?:INC|DEC) (balloons_left|balloons_popped|items_found|zp_[0-9A-F]{2}|ram_0[0-9A-F]{3})$', l)
        if mi and not mi.group(1).startswith('ent_'): counters.add(mi.group(0))
        if re.match(r'^(INC|DEC) ent_', l): pass
        prev = l
    rows.append((t, name, labels[name], len(lines), sorted(set(becomes), key=becomes.index), sorted(set(sfx)), sorted(tags), sorted(counters)))
os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
with open(os.path.join(ROOT, 'docs/entity_handlers.md'), 'w') as f:
    f.write('# Entity handlers (bank 5)\n\nGenerated by `tools/summarize_handlers.py` from `src/bank5.s`; static analysis only (handler extents are estimated, so the\nlists may include a little neighbouring code or miss code reached through other jumps).\n\n')
    f.write('| Type | Handler | Lines | Becomes (type) | Sound effects | Calls | Counters |\n|---|---|---|---|---|---|---|\n')
    for t, name, ln, n, bec, sfx, tags, cnt in rows:
        f.write(f"| ${t:02X} | `{name}` | {n} | {', '.join('$' + b for b in bec) or '-'} | {', '.join(sfx) or '-'} | {', '.join(tags) or '-'} | {', '.join(cnt[:4]) or '-'} |\n")
print(len(rows), 'handlers summarised')
