#!/usr/bin/env python3
"""Generate tools/hints_entity.txt: entity behaviour dispatch table in bank 5 ($8AF5, indexed by ent_type * 2).
The update loop in the fixed bank ($FAFE..) reads the handler for each active entity and JMPs to it (bank 5 mapped).
Type 0 = no entity (its table word is junk); the do-nothing handler is shared by every unused type."""
import os, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b5 = d[16 + 5 * 16384:16 + 6 * 16384]
def wd(a): return b5[a - 0x8000] | b5[a - 0x7FFF] << 8
T, N = 0x8AF5, 160
# what the handler does, as read from the code (stage 0 types); others are undescribed
DESCR = {0x01: 'balloon (goal): popped by pecking (player state $07 overlapping), sets the respawn point, becomes $02, decrements balloons_left; at 0 the level ends',
         0x02: 'popped balloon: rises along a displacement table',
         0x08: 'hidden bonus item: on touch plays sfx $19, becomes $07 and increments items_found',
         0x2E: 'follows a scripted displacement path (table at $9CA2, ent_radius = step; $FF loops)',
         0x4E: 'patrol creature: walks 1 px in X every ((ent_angle>>3)&7)+1 frames, turns at walls/ledges, becomes $4F when ent_radius expires',
         0x51: 'orbiter, inactive: saves its position as the circle centre and becomes $52',
         0x52: 'orbiter: ent_angle += ent_param2 each frame, placed on a circle of radius ent_radius around the centre'}
h = {t: wd(T + 2 * t) for t in range(1, N + 1)}
count = collections.Counter(h.values()); noop = count.most_common(1)[0][0]
out = ['; generated by tools/gen_entity_hints.py -- do not edit by hand',
       f'name 5 {T:X} EntityHandlerTable', f'struct 5 {T:X} 1 w   ; type 0 (unused)', f'words 5 {T + 2:X} {N} 5',
       f'name 5 {noop:X} Ent_Noop']
first = {}
for t in sorted(h):
    if h[t] != noop: first.setdefault(h[t], t)
for a, t in sorted(first.items(), key=lambda kv: kv[1]):
    out.append(f'name 5 {a:X} Ent{t:02X}_Update   ; handler for ent_type ${t:02X}' + (f' - {DESCR[t]}' if t in DESCR else '') + (f' (also {", ".join("$%02X" % u for u in h if h[u] == a and u != t)})' if sum(1 for u in h if h[u] == a) > 1 else ''))
open(os.path.join(ROOT, 'tools/hints_entity.txt'), 'w').write('\n'.join(out) + '\n')
print(len(first), 'distinct handlers; noop handler', hex(noop), 'for', count[noop], 'types')
