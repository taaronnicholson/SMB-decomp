#!/usr/bin/env python3
"""Find ASCII text strings (forward, or stored reversed) and emit tools/hints_text.txt."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
WORDS = ('THE', 'AND', 'FOR', 'YOU', 'ALL', 'NOW', 'OF', 'TO', 'BY', 'INC', 'STAGE', 'FIND', 'GAME', 'OVER',
         'START', 'SCORE', 'PUSH', 'HIGH', 'LIFE', 'LICENSED', 'PUBLISHED', 'TRADEMARK', 'PAUSED', 'HELP',
         'CLEAR', 'QUEST', 'BY ', 'EGG', 'MUSIC', 'GRAPHICS', 'PROGRAMMED', 'DEDICATED', 'THANKS')
pat = re.compile(rb'[A-Z0-9 :!.,\'\-]{6,}')
out = ['; generated by tools/gen_text_hints.py']
n = 0
for bank in range(8):
    b = d[16 + bank * 16384:16 + (bank + 1) * 16384]
    base = 0xC000 if bank == 7 else 0x8000
    for m in pat.finditer(b):
        s = m.group().decode()
        if len(set(s)) < 4 or s.count(' ') > len(s) // 2: continue
        fs = sum(w in s for w in WORDS); rs = sum(w in s[::-1] for w in WORDS)
        if not (fs or rs): continue
        rev = rs > fs
        out.append(f'text {"f" if bank == 7 else bank} {base + m.start():X} {len(s)}{" rev" if rev else ""}')
        n += 1
open(os.path.join(ROOT, 'tools/hints_text.txt'), 'w').write('\n'.join(out) + '\n')
print('text strings:', n)
