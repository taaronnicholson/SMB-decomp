#!/usr/bin/env python3
"""Generate tools/hints_spawn.txt: per-area entity spawn lists in bank 1 (pointer table at $9F25).

Per area: setup-action bytes ended by $FF, then 10-byte entity records ended by $FF:
  type, Y (16-bit), X (16-bit), flags, four parameters (the 4th..7th ends up in ent_param/angle/radius/...).
Then: a word offset (zp_B4) to a per-row table, 3-byte entries grouped by $FF and ended by $FE, and 8-byte one-time objects
(flag bit in ram $0733, type, Y, X, flags, frame) ended by $FF. Some pointers land right before code, so only the parsed span is data."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b1 = d[16 + 16384:16 + 2 * 16384]
def by(a): return b1[a - 0x8000]
def wd(a): return by(a) | by(a + 1) << 8
T, N = 0x9F25, 24
b0 = d[16:16 + 16384]
HEIGHT = [b0[(b0[0x83B9 - 0x8000 + i] | b0[0x83D1 - 0x8000 + i] << 8) - 0x8000 + 4] for i in range(N)]
out = ['; generated by tools/gen_spawn_hints.py -- do not edit by hand',
       f'name 1 {T:X} AreaSpawnPtrs', f'dwords 1 {T:X} {N}']
areas = {}
for a in range(N): areas.setdefault(wd(T + 2 * a), []).append(a)
PS = sorted(areas)
for k, p in enumerate(PS):
    nxt = PS[k + 1] if k + 1 < len(PS) else 0xBFFF
    i = p; acts = 0
    while by(i) != 0xFF: i += 1; acts += 1
    start_ents = i + 1; n = 0; i = start_ents
    while by(i) != 0xFF and n < 40: i += 10; n += 1
    ent_end = i
    rows = [f'struct 1 {p:X} 1 ' + 'b' * (acts + 1)]
    if n: rows.append(f'struct 1 {start_ents:X} {n} bwwbbbbb')
    rows.append(f'struct 1 {i:X} 1 b')
    i += 1
    # "zp_B4" block: [word: offset to row table][3-byte entries (kind, column, value) in lists ended by $FF][$FE]
    #                [8-byte one-time objects ended by $FF][row table: one word per map row = offset of that row's list]
    B4 = i; rt = B4 + wd(B4); a = B4 + 2; ok = 0 < wd(B4) < 600; groups = trip = 0
    while ok and by(a) != 0xFE and a < rt:
        if by(a) == 0xFF: a += 1; groups += 1
        else: a += 3; trip += 1
    ok = ok and by(a) == 0xFE and rt < nxt
    one = 0; hrows = 0
    if ok:
        rows.append(f'struct 1 {B4:X} 1 w   ; offset to the row table')
        b = B4 + 2
        while b < a:
            if by(b) == 0xFF: rows.append(f'struct 1 {b:X} 1 b'); b += 1
            else: rows.append(f'struct 1 {b:X} 1 bbb'); b += 3
        rows.append(f'struct 1 {a:X} 1 b')
        b = a + 1
        while by(b) != 0xFF and b < rt: b += 8; one += 1
        if one: rows.append(f'struct 1 {a + 1:X} {one} bbwwbb')
        if b == rt - 1 or b < rt:
            rows.append(f'struct 1 {b:X} 1 b')
        hrows = min(HEIGHT[areas[p][0]], (nxt - rt) // 2)
        rows.append(f'struct 1 {rt:X} 1 ' + 'w' * hrows + '   ; per-row offsets to entry lists')
        end = rt + 2 * hrows
    else:
        end = ent_end + 1
    out.append(f'blob 1 {p:X} {end - p} AreaSpawn{k} spawn data for area(s) {",".join(map(str, areas[p]))}: {acts} setup actions, {n} entities' + (f', {trip} look-ahead entries, {one} one-time objects, {hrows} rows' if ok else ''))
    out += rows
open(os.path.join(ROOT, 'tools/hints_spawn.txt'), 'w').write('\n'.join(out) + '\n')
print(len(areas), 'spawn lists')
