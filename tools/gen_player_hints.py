#!/usr/bin/env python3
"""Generate tools/hints_player.txt: the player state dispatch table (bank 2 $B5AA, indexed by player_state; handlers in the fixed bank)."""
import os, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b2 = d[16 + 2 * 16384:16 + 3 * 16384]
def wd(a): return b2[a - 0x8000] | b2[a - 0x7FFF] << 8
T, N = 0xB5AA, 32
out = ['; generated by tools/gen_player_hints.py -- do not edit by hand',
       f'name 2 {T:X} PlayerStateHandlers', f'words 2 {T:X} {N}']
first = {}
for s in range(N): first.setdefault(wd(T + 2 * s), s)
for a, s in sorted(first.items(), key=lambda kv: kv[1]):
    also = [t for t in range(N) if wd(T + 2 * t) == a and t != s]
    out.append(f'name f {a:X} PlayerState{s:02X}   ; player_state ${s:02X}' + (f' (also {", ".join("$%02X" % t for t in also)})' if also else ''))
open(os.path.join(ROOT, 'tools/hints_player.txt'), 'w').write('\n'.join(out) + '\n')
print(len(first), 'distinct player state handlers')
