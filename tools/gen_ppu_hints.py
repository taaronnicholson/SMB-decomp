#!/usr/bin/env python3
"""Generate tools/hints_ppu.txt: PPU update-buffer copy handlers (bank 0 table at $8000/$8020)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b = d[16:16 + 16384]
out = ['; generated by tools/gen_ppu_hints.py',
       'lohi 0 8000 8020 32 -     ; PPU buffer copy handlers: low bytes at $8000, high bytes at $8020',
       'name 0 8000 PPUCopyLo', 'name 0 8020 PPUCopyHi',
       'refexpr 7FFF 0 8000 -1    ; LDA $7FFF,y  == PPUCopyLo-1,y   (y = length 1..32)',
       'refexpr 801F 0 8020 -1    ; LDA $801F,y  == PPUCopyHi-1,y']
for i in range(32):
    t = b[i] | b[0x20 + i] << 8
    out.append(f'name f {t:X} PPUCopy{i + 1}')
open(os.path.join(ROOT, 'tools/hints_ppu.txt'), 'w').write('\n'.join(out) + '\n')
