#!/usr/bin/env python3
"""Generate tools/hints_palette.txt: the 9 palette sets in bank 0 (pointer tables at $8040/$8049).
Each set is 16 NES palette bytes = 4 palettes of 4 colours; byte 0 of every palette is replaced by the backdrop colour.
Set 0 ($8052) holds the shared sprite palettes; sets 1-7 are background palettes (area header byte 5 = set number)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
b0 = d[16:16 + 16384]
def by(a): return b0[a - 0x8000]
LO, HI, N, END = 0x8040, 0x8049, 9, 0x8108
ptrs = [by(LO + i) | by(HI + i) << 8 for i in range(N)]
out = ['; generated by tools/gen_palette_hints.py -- do not edit by hand',
       f'dlohi 0 {LO:X} {HI:X} {N}', f'name 0 {LO:X} PaletteSetPtrLo', f'name 0 {HI:X} PaletteSetPtrHi']
for i, p in enumerate(ptrs):
    nxt = ptrs[i + 1] if i + 1 < N else END
    nm = 'SpritePalettes' if i == 0 else f'PaletteSet{i}'
    out.append(f'blob 0 {p:X} {nxt - p} {nm} NES palette bytes ({"sprite palettes, backdrop placeholder 00" if i == 0 else "background palettes"}); set {i}')
    out.append(f'struct 0 {p:X} 1 ' + 'b' * (nxt - p))
open(os.path.join(ROOT, 'tools/hints_palette.txt'), 'w').write('\n'.join(out) + '\n')
print(N, 'palette sets')
