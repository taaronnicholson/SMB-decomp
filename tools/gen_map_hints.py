#!/usr/bin/env python3
"""Generate tools/hints_maps.txt: area maps (data starts at base + 2*width, (height-2) rows) and tileset planes/attributes."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'rom/game.nes'), 'rb').read()
PRG = [d[16 + i * 16384:16 + (i + 1) * 16384] for i in range(8)]
b0 = PRG[0]
def by(a): return b0[a - 0x8000]
def wd(a): return by(a) | by(a + 1) << 8
LO, HI, BANK, N = 0x83B9, 0x83D1, 0x83E9, 24
out = ['; generated by tools/gen_map_hints.py -- do not edit by hand']
maps = {}
for i in range(N):
    h = by(LO + i) | by(HI + i) << 8; bank = by(BANK + i)
    base = wd(h + 1); width = 8 << by(h + 3); rows = by(h + 4)
    start = base + 2 * width
    maps.setdefault((bank, start), (width, rows - 2, []))[2].append(i)
for (bank, start), (w, r, areas) in sorted(maps.items()):
    if not (0x8000 <= start and start + w * r <= 0xC000): continue
    nm = f'AreaMap{areas[0]}'
    out.append(f'blob {bank} {start:X} {w * r} {nm} tile map for area(s) {",".join(map(str, areas))}: {w} x {r} metatiles (rows 2..), one byte per 16x16 tile')
# tilesets: 8-byte records at $8C9B + 8*t (t = 1..5 compressed tilesets in bank 4)
for t in range(1, 6):
    rec = 0x8C9B + 8 * t
    props, gfx, planes, attr = wd(rec), wd(rec + 2), wd(rec + 4), wd(rec + 6)
    out.append(f'name 0 {rec:X} TilesetRecord{t}')
    out.append(f'struct 0 {rec:X} 1 wwww   ; props block, graphics block, planes, attribute plane')
    out.append(f'blob 0 {planes:X} 960 Tileset{t}_Planes metatile tile numbers for tileset {t}: top-left, top-right, bottom-left, bottom-right planes of 240 entries')
    out.append(f'blob 0 {attr:X} 240 Tileset{t}_Attr palette (0-3) per metatile for tileset {t}')
# tileset 0 (areas with header byte 11 = 0) keeps everything in bank 0: LZ props and graphics, raw planes and attributes
rec = 0x8C9B; props, gfx, planes, attr = wd(rec), wd(rec + 2), wd(rec + 4), wd(rec + 6)
out.append(f'name 0 {rec:X} TilesetRecord0')
out.append(f'struct 0 {rec:X} 1 wwww   ; props block, graphics block, planes, attribute plane')
out.append(f'blob 0 {gfx:X} {planes - gfx} Tileset0_Gfx LZ-compressed tile graphics for tileset 0 (1392 bytes decompressed)')
out.append(f'blob 0 {planes:X} 960 Tileset0_Planes metatile tile numbers for tileset 0')
out.append(f'blob 0 {attr:X} 240 Tileset0_Attr palette (0-3) per metatile for tileset 0')
out.append(f'blob 0 {props:X} 13 Tileset0_Props LZ-compressed tile property table for tileset 0 (120 bytes decompressed)')
open(os.path.join(ROOT, 'tools/hints_maps.txt'), 'w').write('\n'.join(out) + '\n')
print(len(maps), 'maps')
